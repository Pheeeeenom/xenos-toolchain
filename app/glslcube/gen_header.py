#!/usr/bin/env python3
"""Compiles the cube's shaders FROM GLSL at build time and embeds them.

glsl_vs/glsl_ps come from xsc/testdata/{spincube.vert,modulate.frag} via
glslang -> xsc.lower (the full open GLSL->Xenos pipeline). The HUD shaders
(xost_vs1/xost_ps0) are the pre-built hand shaders. This app is the proof
that real GLSL renders on the console through our toolchain.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))
import xsc.spirv as spirv  # noqa: E402
from xsc.lower import lower  # noqa: E402

HERE = Path(__file__).resolve().parent
OUT = HERE / "source" / "xost_shaders.h"
GLSLANG = ROOT / "tools" / "glslang" / "bin" / "glslang.exe"
TD = ROOT / "xsc" / "testdata"


def glsl_to_bin(src: Path) -> bytes:
    spv = src.with_suffix(src.suffix + ".spv")
    subprocess.run([str(GLSLANG), "-G", "--target-env", "opengl",
                    str(src), "-o", str(spv)], check=True,
                   capture_output=True)
    return lower(spirv.Module.parse(spv.read_bytes()))


def c_array(name: str, data: bytes) -> str:
    lines = [f"static unsigned char {name}[] __attribute__((aligned(4))) = {{"]
    for i in range(0, len(data), 12):
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
                     + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    blobs = {
        "glsl_vs": glsl_to_bin(TD / "spincube.vert"),
        "glsl_ps": glsl_to_bin(TD / "modulate.frag"),
    }
    for name in ("xost_vs1", "xost_ps0"):
        blobs[name] = (ROOT / "examples" / "out" / f"{name}.bin").read_bytes()

    parts = ["/* generated by gen_header.py - cube shaders compiled FROM "
             "GLSL via xsc; do not edit. */", ""]
    for name, data in blobs.items():
        parts.append(c_array(name, data))
        parts.append("")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}  (glsl_vs {len(blobs['glsl_vs'])} B, "
          f"glsl_ps {len(blobs['glsl_ps'])} B)")


if __name__ == "__main__":
    main()
