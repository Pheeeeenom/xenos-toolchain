#!/usr/bin/env python3
"""Extracts the proven corpus instruction-field templates (exactly as
examples/author_combiners.py does) and writes xcomb/xcomb_templates.h.

ALU template:    corpus vs0  slot 13 via author_passthrough.alu_fields
tfetch template: corpus ps_fb0 slot 3 via author_textured.tf_fields

Float-valued tfetch fields (lod_bias, offset_x/y/z) are stored as their RAW
encoded integer field values (lod_bias raw = value*16, offsets raw = value*2;
all zero in the corpus template), so the C side never touches floats.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "examples"))

import xdis.xenos_ucode as xu  # noqa: E402
from author_passthrough import alu_fields, corpus_records  # noqa: E402
from author_textured import tf_fields  # noqa: E402

ALU_ORDER = [
    "vector_opcode", "scalar_opcode", "vector_dest",
    "is_vector_dest_relative", "vector_write_mask", "vector_clamp",
    "scalar_dest", "is_scalar_dest_relative", "scalar_write_mask",
    "scalar_clamp", "is_export", "abs_constants", "is_predicated",
    "predicate_condition", "is_const_0_addressed", "is_const_1_addressed",
    "is_const_address_register_relative",
    "src1_reg", "src1_is_temp", "src1_swizzle", "src1_negate",
    "src2_reg", "src2_is_temp", "src2_swizzle", "src2_negate",
    "src3_reg", "src3_is_temp", "src3_swizzle", "src3_negate",
]

TF_ORDER = [
    "opcode", "src", "src_swizzle", "is_src_relative", "dest",
    "dest_swizzle", "is_dest_relative", "fetch_constant_index",
    "fetch_valid_only", "unnormalized_coordinates", "mag_filter",
    "min_filter", "mip_filter", "aniso_filter", "arbitrary_filter",
    "vol_mag_filter", "vol_min_filter", "use_computed_lod",
    "use_register_lod", "use_register_gradients", "sample_location",
    "lod_bias_raw", "dimension", "offset_x_raw", "offset_y_raw",
    "offset_z_raw", "is_predicated", "predicate_condition",
]

# decoder accessors return scaled floats; raw field = float * scale
_TF_FLOAT_SCALE = {"lod_bias": 16, "offset_x": 2, "offset_y": 2,
                   "offset_z": 2}


def _raw_int(name: str, value) -> int:
    if name in _TF_FLOAT_SCALE:
        raw = float(value) * _TF_FLOAT_SCALE[name]
        assert raw == int(raw), f"{name}={value} not representable"
        return int(raw)
    if isinstance(value, bool):
        return 1 if value else 0
    return int(value)


def main():
    vs0 = corpus_records("vs0")
    ps0 = corpus_records("ps_fb0")
    alu = alu_fields(xu.AluInstruction(*vs0["alu13"].raw))
    tf = tf_fields(xu.TextureFetchInstruction(*ps0["tfetch3"].raw))

    alu_c = {k: _raw_int(k, alu[k]) for k in ALU_ORDER}
    tf_c = {}
    for k in TF_ORDER:
        src_key = k[:-4] if k.endswith("_raw") else k
        tf_c[k] = _raw_int(src_key, tf[src_key])

    lines = []
    lines.append("/* Generated by tools/gen_templates.py - do not edit.")
    lines.append(" * Corpus-proven instruction field templates:")
    lines.append(" *   alu:    vs0 slot 13  (max oN <- r0, the mov template)")
    lines.append(" *   tfetch: ps_fb0 slot 3 (tfetch2D, fetch constant 0)")
    lines.append(" * Float fields are stored as RAW encoded integer field")
    lines.append(" * values (lod_bias_raw = bias*16, offset_*_raw = off*2).")
    lines.append(" */")
    lines.append("#ifndef XCOMB_TEMPLATES_H")
    lines.append("#define XCOMB_TEMPLATES_H")
    lines.append("")
    lines.append("typedef struct {")
    for k in ALU_ORDER:
        lines.append(f"    int {k};")
    lines.append("} xcomb_alu_template;")
    lines.append("")
    lines.append("typedef struct {")
    for k in TF_ORDER:
        lines.append(f"    int {k};")
    lines.append("} xcomb_tfetch_template;")
    lines.append("")
    lines.append("static const xcomb_alu_template XCOMB_ALU_TEMPLATE = {")
    for k in ALU_ORDER:
        lines.append(f"    /* {k:36s} */ {alu_c[k]},")
    lines.append("};")
    lines.append("")
    lines.append("static const xcomb_tfetch_template XCOMB_TFETCH_TEMPLATE"
                 " = {")
    for k in TF_ORDER:
        lines.append(f"    /* {k:36s} */ {tf_c[k]},")
    lines.append("};")
    lines.append("")
    lines.append("#endif /* XCOMB_TEMPLATES_H */")

    out = ROOT / "xcomb" / "xcomb_templates.h"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {out} ({len(ALU_ORDER)} ALU fields, "
          f"{len(TF_ORDER)} tfetch fields)")


if __name__ == "__main__":
    main()
