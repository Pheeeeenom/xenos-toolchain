#!/usr/bin/env python3
"""Regenerates source/xost_shaders.h: vs2, the 6-mode combiner bank,
and the HUD pair (vs1/ps0)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = Path(__file__).resolve().parent / "source" / "xost_shaders.h"

BANK = ["comb_0_modulate", "comb_1_tex_prim", "comb_2_lerp_pe_t",
        "comb_3_decal", "comb_4_shade", "comb_5_inv_tex_p"]


def c_array(name: str, data: bytes) -> str:
    lines = [f"static unsigned char {name}[] __attribute__((aligned(4))) = {{"]
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
        lines.append(f"\t{chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = ["/* generated by gen_header.py - do not edit. */", ""]
    names = []
    for src in ["xost_vs2", "xost_vs1", "xost_ps0"] + BANK:
        cname = src.replace("comb_", "comb")
        names.append(cname)
        data = (ROOT / "examples" / "out" / f"{src}.bin").read_bytes()
        parts.append(c_array(cname, data))
        parts.append("")
    bank = ", ".join(n for n in names if n.startswith("comb"))
    parts.append(f"static unsigned char *comb_bank[6] = {{ {bank} }};")
    parts.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
