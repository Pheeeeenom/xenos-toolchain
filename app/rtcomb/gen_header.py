#!/usr/bin/env python3
"""Regenerates source/xost_shaders.h for the rtcomb demo.

Unlike app/combiner, only the vertex shaders and the HUD pixel shader are
pre-generated here: every cube pixel shader is generated AT RUNTIME on the
console by xcomb_generate().
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = Path(__file__).resolve().parent / "source" / "xost_shaders.h"


def c_array(name: str, data: bytes) -> str:
    lines = [f"static unsigned char {name}[] __attribute__((aligned(4))) = {{"]
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
        lines.append(f"\t{chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = ["/* generated by gen_header.py - do not edit. */", ""]
    for src in ["xost_vs2", "xost_vs1", "xost_ps0"]:
        data = (ROOT / "examples" / "out" / f"{src}.bin").read_bytes()
        parts.append(c_array(src, data))
        parts.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
